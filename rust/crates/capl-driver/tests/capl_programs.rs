use capl_diag::Stage;
use capl_ast::Decl;
use capl_driver::{compile, BackendId, Options};

const PROGRAMS: &[(&str, &str)] = &[
    ("hello", include_str!("programs/hello.can")),
    ("bus", include_str!("programs/bus.can")),
    ("algorithm", include_str!("programs/algorithm.can")),
    ("types", include_str!("programs/types.can")),
    ("state", include_str!("programs/state.can")),
];

fn build(name: &str, source: &str) -> capl_driver::Output {
    compile(
        source,
        Options {
            file_name: format!("{name}.can"),
            backends: vec![BackendId::Wasm, BackendId::C, BackendId::Ast],
        },
    )
}

fn handler_count(out: &capl_driver::Output) -> usize {
    out.unit
        .as_ref()
        .map(|unit| unit.decls.iter().filter(|decl| matches!(decl, Decl::Handler(_))).count())
        .unwrap_or(0)
}

#[test]
fn real_capl_programs_compile_through_every_backend() {
    for (name, source) in PROGRAMS {
        let out = build(name, source);
        assert!(out.ok, "{name} failed: {:?}", out.diagnostics);
        assert!(out.diagnostics.is_empty(), "{name} emitted diagnostics: {:?}", out.diagnostics);
        assert!(!out.ast_json.is_empty(), "{name} did not produce AST JSON");
        assert!(out.c.as_ref().is_some_and(|c| c.contains("generated by capl")), "{name} did not produce C");
        let wasm = out.wasm.as_ref().unwrap_or_else(|| panic!("{name} did not produce wasm"));
        assert_eq!(&wasm.bytes[..4], b"\0asm", "{name} has an invalid wasm header");
        assert!(!wasm.wat.is_empty(), "{name} did not produce a WAT listing");
    }
}

#[test]
fn hello_program_exposes_start_and_timer_metadata() {
    let out = build("hello", include_str!("programs/hello.can"));
    let sema = out.sema.as_ref().expect("semantic result");
    assert_eq!(handler_count(&out), 4);
    assert_eq!(sema.timers.len(), 1);
    assert!(out.wasm.unwrap().exports.iter().any(|e| e == "on_start"));
}

#[test]
fn bus_program_lowers_host_calls_and_message_handlers() {
    let out = build("bus", include_str!("programs/bus.can"));
    assert_eq!(handler_count(&out), 3);
    let wat = out.wasm.unwrap().wat;
    assert!(wat.contains("call 2"), "cyclic timer call missing from WAT");
    assert!(wat.contains("call 4"), "message output call missing from WAT");
    assert!(wat.contains("on_message_0x100"));
}

#[test]
fn algorithm_program_uses_native_64_bit_and_float_instructions() {
    let out = build("algorithm", include_str!("programs/algorithm.can"));
    let wat = out.wasm.unwrap().wat;
    assert!(wat.contains("i64.mul"), "64-bit arithmetic was not lowered natively");
    assert!(wat.contains("f64.sqrt"), "sqrt was not lowered to f64.sqrt");
    assert!(wat.contains("call 8"), "pow host call missing");
}

#[test]
fn state_program_covers_key_handlers_and_timer_cancellation() {
    let out = build("state", include_str!("programs/state.can"));
    assert_eq!(handler_count(&out), 5);
    let wat = out.wasm.unwrap().wat;
    assert!(wat.contains("on_key_103"), "g key handler missing");
    assert!(wat.contains("call 3"), "cancelTimer host call missing");
}

#[test]
fn invalid_capl_reports_parse_or_sema_diagnostics_without_artifacts() {
    let out = build("invalid", include_str!("programs/invalid.can"));
    assert!(!out.ok);
    assert!(out.wasm.is_none());
    assert!(out.c.is_none());
    assert!(!out.diagnostics.is_empty());
    assert!(out.diagnostics.iter().any(|d| matches!(d.stage, Stage::Parse | Stage::Sema)));
}
