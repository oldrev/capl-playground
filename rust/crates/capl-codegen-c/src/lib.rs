//! `capl-codegen-c` — prints portable C99 from the decorated AST.
//!
//! The emitted file only needs `libcapl` (14 shim functions) to link, which
//! makes it a convenient way to run CAPL logic inside an existing C test bench
//! or to cross-compile a node for a target that has no wasm runtime.
#![forbid(unsafe_code)]

use capl_ast::*;
use capl_sema::{msg_accessor, SemaResult, MSG_FIELDS};

pub const PREAMBLE: &str = r#"/* generated by capl --backend=c */
#include <stdint.h>
#include <string.h>

typedef struct { uint32_t id; int32_t dlc; uint8_t data[8];
                 int32_t can; int32_t dir; int32_t rtr; int32_t time; } CaplMessage;
typedef int32_t CaplTimer;

extern void    capl_write(const char *fmt, ...);
extern void    capl_set_timer(CaplTimer t, int32_t ms);
extern void    capl_set_timer_cyclic(CaplTimer t, int32_t ms);
extern void    capl_cancel_timer(CaplTimer t);
extern void    capl_output(CaplMessage *m);
extern int32_t capl_time_now(void);
extern int32_t capl_random(int32_t n);

#define CAPL_B(m, i) ((m)->data[(i)])
#define CAPL_W(m, i) ((uint16_t)((m)->data[(i)*2] | ((m)->data[(i)*2+1] << 8)))

static CaplMessage *this_msg;
"#;

pub fn c_type(t: &Ty) -> String {
    match t.kind {
        TyKind::Void => "void".into(), TyKind::Char => "char".into(), TyKind::Byte => "uint8_t".into(),
        TyKind::Int => "int16_t".into(), TyKind::Word => "uint16_t".into(), TyKind::Long => "int32_t".into(),
        TyKind::Dword => "uint32_t".into(), TyKind::Int64 => "int64_t".into(), TyKind::Qword => "uint64_t".into(),
        TyKind::Float | TyKind::Double => "double".into(), TyKind::Timer | TyKind::MsTimer => "CaplTimer".into(),
        TyKind::Message => "CaplMessage".into(), TyKind::Array => t.elem.as_ref().map(|e| c_type(e)).unwrap_or_else(|| "int32_t".into()),
        TyKind::Struct => t.name.clone().map(|n| format!("struct {n}")).unwrap_or_else(|| "int32_t".into()),
        TyKind::Error => "int32_t".into(),
    }
}

fn c_array_decl(t: &Ty) -> (String, String) {
    if t.kind == TyKind::Array {
        let (base, suffix) = t.elem.as_deref().map(c_array_decl).unwrap_or_else(|| ("int32_t".into(), String::new()));
        (base, format!("[{}]{}", t.len.unwrap_or(1), suffix))
    } else {
        (c_type(t), String::new())
    }
}

pub struct CBackend<'s> {
    sema: &'s SemaResult,
    out: String,
    indent: usize,
}

impl<'s> CBackend<'s> {
    pub fn new(sema: &'s SemaResult) -> Self {
        Self { sema, out: String::new(), indent: 0 }
    }

    fn line(&mut self, s: &str) {
        for _ in 0..self.indent {
            self.out.push_str("  ");
        }
        self.out.push_str(s);
        self.out.push('\n');
    }

    pub fn emit(mut self, unit: &Unit) -> String {
        self.out.push_str(PREAMBLE);
        self.line("");
        for decl in &unit.decls {
            if let Decl::Enum(e) = decl {
                self.line(&format!("enum {} {{", if e.name.is_empty() { "CaplAnonEnum" } else { &e.name }));
                self.indent += 1;
                for item in &e.items {
                    self.line(&format!("{} = {},", item.name, item.resolved));
                }
                self.indent -= 1;
                self.line("};");
            }
            if let Decl::Struct(s) = decl {
                self.line(&format!("struct {} {{", s.name)); self.indent += 1;
                if let Some(ty) = &s.ty { let _ = ty; }
                for f in &s.fields {
                    let ty = c_type(&f.decl_ty);
                    let dims = f.dims.iter().map(|d| format!("[{}]", self.expr(d))).collect::<String>();
                    self.line(&format!("{} {}{};", ty, f.name, dims));
                }
                self.indent -= 1; self.line("};");
            }
        }
        for &id in &self.sema.globals {
            let Some(v) = self.sema.var(id) else { continue };
            let decl = match v.ty.kind {
                TyKind::Timer | TyKind::MsTimer => {
                    format!("static CaplTimer {} = {};", v.name, v.timer_id.unwrap_or(0))
                }
                TyKind::Message => format!(
                    "static CaplMessage {} = {{ 0x{:x}u, 8, {{0}}, 1, 0, 0, 0 }};",
                    v.name,
                    v.ty.msg_id.unwrap_or(0)
                ),
                TyKind::Array => {
                    let (ty, dims) = c_array_decl(&v.ty);
                    format!("static {} {}{};", ty, v.name, dims)
                }
                TyKind::Struct => format!("static {} {};", c_type(&v.ty), v.name),
                _ => format!("static {} {};", c_type(&v.ty), v.name),
            };
            self.line(&decl);
        }
        self.line("");

        for decl in &unit.decls {
            match decl {
                Decl::Func(f) => {
                    let params = if f.params.is_empty() {
                        "void".to_string()
                    } else {
                        f.params
                            .iter()
                            .map(|p| {
                                if matches!(p.decl_ty.kind, TyKind::Array | TyKind::Struct) {
                                    format!("{} *{}", c_type(&p.decl_ty), p.name)
                                } else {
                                    format!("{} {}", c_type(&p.decl_ty), p.name)
                                }
                            })
                            .collect::<Vec<_>>()
                            .join(", ")
                    };
                    let ret = if matches!(f.ret_ty.kind, TyKind::Array | TyKind::Struct) { format!("{} *", c_type(&f.ret_ty)) } else { c_type(&f.ret_ty) };
                    let sig = format!("{} {}({})", ret, f.name, params);
                    self.line(&sig);
                    self.stmt(&f.body);
                    self.line("");
                }
                Decl::Handler(h) => {
                    self.line(&format!("void {}(void)", h.export_name));
                    self.stmt(&h.body);
                    self.line("");
                }
                _ => {}
            }
        }

        self.line("typedef struct { const char *event; uint32_t selector; void (*fn)(void); } CaplHandler;");
        self.line("const CaplHandler capl_handlers[] = {");
        self.indent += 1;
        for decl in &unit.decls {
            if let Decl::Handler(h) = decl {
                let sel = match &h.event {
                    EventSpec::Message { id: Some(id), .. } => *id,
                    EventSpec::Key { key: Some(k), .. } => *k as u32,
                    _ => 0,
                };
                self.line(&format!("{{ \"{}\", 0x{:x}u, {} }},", h.export_name, sel, h.export_name));
            }
        }
        self.line("{ 0, 0, 0 }");
        self.indent -= 1;
        self.line("};");
        self.out
    }

    fn stmt(&mut self, s: &Stmt) {
        match &s.kind {
            StmtKind::Block { stmts } => {
                self.line("{");
                self.indent += 1;
                for st in stmts {
                    self.stmt(st);
                }
                self.indent -= 1;
                self.line("}");
            }
            StmtKind::Expr { expr } => {
                let e = self.expr(expr);
                self.line(&format!("{e};"));
            }
            StmtKind::Decl { decls } => {
                for d in decls {
                    let init = d.init.as_ref().map(|i| format!(" = {}", self.expr(i))).unwrap_or_default();
                    if d.is_array {
                        let dims = if d.dims.is_empty() {
                            "[]".to_string()
                        } else {
                            d.dims.iter().map(|dim| format!("[{}]", self.expr(dim))).collect::<String>()
                        };
                        self.line(&format!("{} {}{}{};", c_type(&d.decl_ty), d.name, dims, init));
                    } else {
                        self.line(&format!("{} {}{};", c_type(&d.decl_ty), d.name, init));
                    }
                }
            }
            StmtKind::If { cond, then, otherwise } => {
                let c = self.expr(cond);
                self.line(&format!("if ({c})"));
                self.stmt(then);
                if let Some(o) = otherwise {
                    self.line("else");
                    self.stmt(o);
                }
            }
            StmtKind::While { cond, body } => {
                let c = self.expr(cond);
                self.line(&format!("while ({c})"));
                self.stmt(body);
            }
            StmtKind::DoWhile { body, cond } => {
                self.line("do");
                self.stmt(body);
                let c = self.expr(cond);
                self.line(&format!("while ({c});"));
            }
            StmtKind::For { init, cond, step, body } => {
                let i = match init.as_deref() {
                    Some(Stmt { kind: StmtKind::Expr { expr }, .. }) => self.expr(expr),
                    _ => String::new(),
                };
                let c = cond.as_ref().map(|c| self.expr(c)).unwrap_or_default();
                let st = step.as_ref().map(|s| self.expr(s)).unwrap_or_default();
                self.line(&format!("for ({i}; {c}; {st})"));
                self.stmt(body);
            }
            StmtKind::Switch { disc, clauses } => {
                let d = self.expr(disc);
                self.line(&format!("switch ({d}) {{"));
                for c in clauses {
                    match &c.test {
                        Some(t) => {
                            let t = self.expr(t);
                            self.line(&format!("case {t}:"));
                        }
                        None => self.line("default:"),
                    }
                    self.indent += 1;
                    for st in &c.body {
                        self.stmt(st);
                    }
                    self.indent -= 1;
                }
                self.line("}");
            }
            StmtKind::Break => self.line("break;"),
            StmtKind::Continue => self.line("continue;"),
            StmtKind::Return { expr } => match expr {
                Some(e) => {
                    let aggregate = e.ty.as_ref().is_some_and(|t| t.kind == TyKind::Struct);
                    let already_address = matches!(e.kind, ExprKind::Ident { sym: Some(id), .. } if self.sema.var(id).is_some_and(|v| v.storage == capl_sema::Storage::Param && v.ty.kind == TyKind::Struct));
                    let e = self.expr(e);
                    let e = if aggregate && !already_address { format!("&{e}") } else { e };
                    self.line(&format!("return {e};"));
                }
                None => self.line("return;"),
            },
            StmtKind::Empty => self.line(";"),
        }
    }

    fn expr(&self, e: &Expr) -> String {
        match &e.kind {
            ExprKind::IntLit { value } => value.to_string(),
            ExprKind::FloatLit { value } => format!("{value:?}"),
            ExprKind::CharLit { value } => format!("{value}"),
            ExprKind::StrLit { value } => format!("{value:?}"),
            ExprKind::Ident { name, .. } => name.clone(),
            ExprKind::This => "this_msg".into(),
            ExprKind::Unary { op, operand, postfix } => {
                let o = self.expr(operand);
                if *postfix {
                    format!("({o}{op})")
                } else {
                    format!("({op}{o})")
                }
            }
            ExprKind::Binary { op, left, right } => {
                format!("({} {} {})", self.expr(left), op, self.expr(right))
            }
            ExprKind::Assign { op, target, value } => {
                if op == "=" && target.ty.as_ref().is_some_and(|t| t.kind == TyKind::Struct) {
                    format!("({} = *{})", self.expr(target), self.expr(value))
                } else {
                    format!("({} {} {})", self.expr(target), op, self.expr(value))
                }
            }
            ExprKind::Cond { cond, then, otherwise } => {
                format!("({} ? {} : {})", self.expr(cond), self.expr(then), self.expr(otherwise))
            }
            ExprKind::Index { base, index } => format!("{}[{}]", self.expr(base), self.expr(index)),
            ExprKind::Member { base, name } => {
                if MSG_FIELDS.iter().any(|(f, _, _)| f == name) {
                    format!("{}->{}", self.msg_ref(base), name)
                } else if self.is_struct_param(base) {
                    format!("{}->{}", self.expr(base), name)
                } else {
                    format!("{}.{}", self.expr(base), name)
                }
            }
            ExprKind::InitList { items } => {
                format!("{{ {} }}", items.iter().map(|i| self.expr(i)).collect::<Vec<_>>().join(", "))
            }
            ExprKind::Call { callee, args, .. } => self.call(callee, args),
        }
    }

    fn msg_ref(&self, e: &Expr) -> String {
        match &e.kind {
            ExprKind::This => "this_msg".into(),
            _ => format!("(&{})", self.expr(e)),
        }
    }

    fn is_struct_param(&self, e: &Expr) -> bool {
        let ExprKind::Ident { sym: Some(id), .. } = e.kind else { return false };
        self.sema.var(id).is_some_and(|v| v.storage == capl_sema::Storage::Param && v.ty.kind == TyKind::Struct)
    }


    fn call(&self, callee: &Expr, args: &[Expr]) -> String {
        if let ExprKind::Member { base, name } = &callee.kind {
            let idx = args.first().map(|a| self.expr(a)).unwrap_or_else(|| "0".into());
            return match msg_accessor(name) {
                Some((1, _)) => format!("CAPL_B({}, {idx})", self.msg_ref(base)),
                Some((2, _)) => format!("CAPL_W({}, {idx})", self.msg_ref(base)),
                _ => format!("CAPL_B({}, {idx})", self.msg_ref(base)),
            };
        }
        let name = match &callee.kind {
            ExprKind::Ident { name, .. } => name.clone(),
            _ => "(*unknown)".into(),
        };
        let a: Vec<String> = args.iter().map(|x| {
            if let Some(id) = match &x.kind { ExprKind::Ident { sym: Some(id), .. } => Some(*id), _ => None } {
                if self.sema.var(id).is_some_and(|v| v.ty.kind == TyKind::Struct) { return format!("&{}", self.expr(x)); }
            }
            self.expr(x)
        }).collect();
        match name.as_str() {
            "write" => format!("capl_write({})", a.join(", ")),
            "setTimer" => format!("capl_set_timer({})", a.join(", ")),
            "setTimerCyclic" => format!("capl_set_timer_cyclic({})", a.join(", ")),
            "cancelTimer" => format!("capl_cancel_timer({})", a.join(", ")),
            "output" => format!("capl_output({})", self.msg_ref(&args[0])),
            "timeNow" => "capl_time_now()".into(),
            "random" => format!("capl_random({})", a.join(", ")),
            "elCount" => args
                .first()
                .and_then(|x| x.ty.as_ref())
                .and_then(|t| t.len)
                .unwrap_or(0)
                .to_string(),
            _ => format!("{name}({})", a.join(", ")),
        }
    }
}

pub fn emit_c(unit: &Unit, sema: &SemaResult) -> String {
    CBackend::new(sema).emit(unit)
}
