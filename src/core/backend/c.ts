/* capl-backend-c — emits portable C99 from the decorated AST
 * (mirror of crates/capl-backend-c). Pure AST consumer: no lookups. */

import * as A from "../ast";
import type { SemaResult } from "../sema";
import { MSG_ACCESSORS } from "../sema";

const CTY: Record<string, string> = {
  void: "void",
  char: "char",
  byte: "uint8_t",
  int: "int16_t",
  word: "uint16_t",
  long: "int32_t",
  dword: "uint32_t",
  int64: "int64_t",
  qword: "uint64_t",
  float: "double",
  double: "double",
  timer: "CaplTimer",
  msTimer: "CaplTimer",
  message: "CaplMessage",
  error: "int32_t",
};

const PREAMBLE = `/* ─────────────────────────────────────────────────────────────
 * Generated by the CAPL compiler — C backend (capl-backend-c)
 * Target: C99 + libcapl runtime shim
 * ───────────────────────────────────────────────────────────── */
#include <stdint.h>
#include <string.h>

typedef struct { uint32_t id; int32_t dlc; uint8_t data[8];
                 int32_t can; int32_t dir; int32_t rtr; int32_t time; } CaplMessage;
typedef int32_t CaplTimer;

/* runtime shim — provided by the embedder (see crates/capl-rt) */
extern void    capl_write(const char *fmt, ...);
extern void    capl_set_timer(CaplTimer t, int32_t ms);
extern void    capl_set_timer_cyclic(CaplTimer t, int32_t ms);
extern void    capl_cancel_timer(CaplTimer t);
extern void    capl_output(CaplMessage *m);
extern int32_t capl_time_now(void);
extern int32_t capl_random(int32_t n);
extern void    capl_can_online(void);
extern void    capl_can_offline(void);
extern void    capl_stop_measurement(void);
extern double  pow(double, double);
extern double  sqrt(double);
extern double  sin(double);
extern double  cos(double);
extern double  floor(double);
extern double  ceil(double);

#define CAPL_B(m, i)  ((m)->data[(i)])
#define CAPL_W(m, i)  ((uint16_t)((m)->data[(i) * 2] | ((m)->data[(i) * 2 + 1] << 8)))
#define CAPL_D(m, i)  ((uint32_t)((m)->data[(i) * 4] | ((m)->data[(i) * 4 + 1] << 8) | \\
                                  ((m)->data[(i) * 4 + 2] << 16) | ((m)->data[(i) * 4 + 3] << 24)))
#define CAPL_SETB(m, i, v) ((m)->data[(i)] = (uint8_t)(v))

static CaplMessage *this_msg;   /* 'this' inside an event handler */
static uint32_t     this_key;
`;

function cty(t: A.Ty): string {
  if (t.kind === "array") return cty(t.elem ?? A.T.char);
  if (t.kind === "struct") return `struct ${t.name ?? "__anon"}`;
  if (t.kind === "enum") return "int32_t"; // CAPL enums are 32-bit here
  return CTY[t.kind] ?? "int32_t";
}

export class CBackend {
  private out: string[] = [];
  private ind = 0;

  constructor(private readonly sema: SemaResult) {}

  private line(s = ""): void {
    this.out.push(s ? "  ".repeat(this.ind) + s : "");
  }

  emit(): string {
    this.out = [PREAMBLE];

    this.line("/* ── types ────────────────────────────────────────────── */");
    for (const d of this.sema.unit.decls) {
      if (d.kind === "StructDecl") this.emitStruct(d);
      else if (d.kind === "EnumDecl") this.emitEnum(d);
      else if (d.kind === "VariablesBlock") {
        for (const td of d.types ?? []) {
          if (td.kind === "StructDecl") this.emitStruct(td);
          else if (td.kind === "EnumDecl") this.emitEnum(td);
        }
      }
    }
    this.line();

    this.line("/* ── globals ─────────────────────────────────────────── */");
    for (const g of this.sema.globals) this.line(this.globalDecl(g));
    if (this.sema.globals.length === 0) this.line("/* (none) */");
    this.line();

    if (this.sema.funcs.length) {
      this.line("/* ── prototypes ──────────────────────────────────────── */");
      for (const f of this.sema.funcs) this.line(`${this.signature(f.decl)};`);
      this.line();
    }

    for (const f of this.sema.funcs) {
      this.line(this.signature(f.decl));
      this.stmt(f.decl.body, true);
      this.line();
    }

    for (const h of this.sema.handlers) {
      this.line(`/* on ${this.eventText(h.event)} */`);
      this.line(`void ${h.exportName}(void)`);
      this.stmt(h.body, true);
      this.line();
    }

    this.line("/* ── event table consumed by the embedder ────────────── */");
    this.line("typedef struct { const char *event; uint32_t selector; void (*fn)(void); } CaplHandler;");
    this.line("const CaplHandler capl_handlers[] = {");
    this.ind++;
    for (const h of this.sema.handlers) {
      const sel = h.event.id ?? (h.event.key ? h.event.key.charCodeAt(0) : 0);
      this.line(`{ "${h.event.kind}", 0x${sel.toString(16)}u, ${h.exportName} },`);
    }
    this.line("{ 0, 0, 0 }");
    this.ind--;
    this.line("};");
    this.line(`const int capl_handler_count = ${this.sema.handlers.length};`);
    this.line("");
    this.line("/* suppress unused warnings for the handler context slots */");
    this.line("void capl_set_context(CaplMessage *m, uint32_t k) { this_msg = m; this_key = k; }");
    return this.out.join("\n");
  }

  private emitEnum(d: A.EnumDecl): void {
    const items = d.items
      .map((it) => (it.resolved === undefined ? it.name : `${it.name} = ${it.resolved}`))
      .join(", ");
    this.line(d.name ? `enum ${d.name} { ${items} };` : `enum { ${items} };`);
  }

  private emitStruct(d: A.StructDecl): void {
    const ty = d.ty;
    this.line(`typedef struct ${d.name}`);
    this.line("{");
    this.ind++;
    for (const f of d.fields) {
      const ft = this.fieldTy(d, f);
      this.line(`${cty(ft)} ${f.name}${this.dimsSuffix(ft)};`);
    }
    this.ind--;
    this.line(`} ${d.name};`);
    if (ty?.size) this.line(`/* sizeof(struct ${d.name}) == ${ty.size} bytes */`);
  }

  private fieldTy(d: A.StructDecl, f: A.StructField): A.Ty {
    const m = d.ty?.members?.find((x) => x.name === f.name);
    return m?.ty ?? f.declTy;
  }

  /** `[3][4]` for nested arrays, empty for scalars */
  private dimsSuffix(ty: A.Ty): string {
    return A.dimsOf(ty)
      .map((n) => `[${n}]`)
      .join("");
  }

  private eventText(e: A.EventSpec): string {
    switch (e.kind) {
      case "timer": return `timer ${e.name}`;
      case "message":
        return `message ${e.wildcard ? "*" : e.id !== undefined ? `0x${e.id.toString(16)}` : e.name}`;
      case "key": return `key '${e.wildcard ? "*" : e.key}'`;
      case "sysvar": return `sysvar ${e.name}`;
      default: return e.kind;
    }
  }

  private globalDecl(g: A.VarSym): string {
    const d = g.decl as A.VarDecl;
    if (g.ty.kind === "timer" || g.ty.kind === "msTimer") {
      return `static CaplTimer ${g.name} = ${g.timerId ?? 0}; /* timer handle */`;
    }
    if (g.ty.kind === "message") {
      const id = g.ty.msgId ?? 0;
      return `static CaplMessage ${g.name} = { 0x${id.toString(16)}u, 8, {0}, 1, 0, 0, 0 };`;
    }
    const init = d.init ? ` = ${this.initText(d.init)}` : "";
    if (g.constValue !== undefined) return `/* ${g.name} is a compile-time constant */`;
    if (g.ty.kind === "array") {
      return `static ${cty(g.ty)} ${g.name}${this.dimsSuffix(g.ty)}${init};`;
    }
    return `static ${cty(g.ty)} ${g.name}${init};`;
  }

  private initText(e: A.Expr): string {
    if (e.kind === "InitList") return `{ ${e.items.map((i) => this.expr(i)).join(", ")} }`;
    return this.expr(e);
  }

  private signature(d: A.FuncDecl): string {
    const ps = d.params.length
      ? d.params
          .map((p) => (p.declTy.kind === "array" ? `${cty(p.declTy)} *${p.name}` : `${cty(p.declTy)} ${p.name}`))
          .join(", ")
      : "void";
    return `${cty(d.retTy)} ${d.name}(${ps})`;
  }

  /* ── statements ─────────────────────────────────────── */
  private stmt(s: A.Stmt, braceOnOwnLine = false): void {
    switch (s.kind) {
      case "Block": {
        this.line(braceOnOwnLine ? "{" : "{");
        this.ind++;
        for (const st of s.stmts) this.stmt(st);
        this.ind--;
        this.line("}");
        break;
      }
      case "ExprStmt": this.line(`${this.expr(s.expr)};`); break;
      case "Empty": this.line(";"); break;
      case "DeclStmt":
        for (const td of s.types ?? []) {
          if (td.kind === "StructDecl") this.emitStruct(td);
          else if (td.kind === "EnumDecl") this.emitEnum(td);
        }
        for (const d of s.decls) {
          const sym = d.sym!;
          if (sym.ty.kind === "array") {
            this.line(`${cty(sym.ty)} ${d.name}${this.dimsSuffix(sym.ty)}${d.init ? ` = ${this.initText(d.init)}` : ""};`);
          } else if (sym.ty.kind === "message") {
            this.line(`CaplMessage ${d.name} = { 0x${(sym.ty.msgId ?? 0).toString(16)}u, 8, {0}, 1, 0, 0, 0 };`);
          } else if (sym.ty.kind === "timer" || sym.ty.kind === "msTimer") {
            this.line(`CaplTimer ${d.name} = ${sym.timerId ?? 0};`);
          } else {
            this.line(`${cty(sym.ty)} ${d.name}${d.init ? ` = ${this.initText(d.init)}` : ""};`);
          }
        }
        break;
      case "If":
        this.line(`if (${this.expr(s.cond)})`);
        this.stmt(s.then);
        if (s.otherwise) {
          this.line("else");
          this.stmt(s.otherwise);
        }
        break;
      case "While":
        this.line(`while (${this.expr(s.cond)})`);
        this.stmt(s.body);
        break;
      case "DoWhile":
        this.line("do");
        this.stmt(s.body);
        this.line(`while (${this.expr(s.cond)});`);
        break;
      case "For": {
        let init = "";
        if (s.init?.kind === "ExprStmt") init = this.expr(s.init.expr);
        else if (s.init?.kind === "DeclStmt") {
          // C99 allows declarations in for-init
          const d = s.init.decls[0];
          init = `${cty(d.sym!.ty)} ${d.name}${d.init ? ` = ${this.initText(d.init)}` : ""}${this.dimsSuffix(d.sym!.ty)}`;
        }
        this.line(`for (${init}; ${s.cond ? this.expr(s.cond) : ""}; ${s.step ? this.expr(s.step) : ""})`);
        this.stmt(s.body);
        break;
      }
      case "Switch":
        this.line(`switch (${this.expr(s.disc)}) {`);
        for (const c of s.clauses) {
          this.line(c.test ? `case ${this.expr(c.test)}:` : "default:");
          this.ind++;
          for (const st of c.body) this.stmt(st);
          this.ind--;
        }
        this.line("}");
        break;
      case "Break": this.line("break;"); break;
      case "Continue": this.line("continue;"); break;
      case "Return": this.line(s.expr ? `return ${this.expr(s.expr)};` : "return;"); break;
    }
  }

  /* ── expressions ────────────────────────────────────── */
  private expr(e: A.Expr): string {
    switch (e.kind) {
      case "IntLit": return String(e.value);
      case "FloatLit": return Number.isInteger(e.value) ? `${e.value}.0` : String(e.value);
      case "CharLit": return e.text;
      case "StringLit": return JSON.stringify(e.value);
      case "Ident": {
        const cv = e.sym?.kind === "var" ? e.sym.constValue : undefined;
        if (cv !== undefined) return String(cv); // enum member / const
        return e.name;
      }
      case "This": return "this_msg";
      case "InitList": return `{ ${e.items.map((i) => this.expr(i)).join(", ")} }`;
      case "Index": return `${this.expr(e.base)}[${this.expr(e.index)}]`;
      case "Member": {
        // message fields are behind a pointer, struct members are not
        if (e.base.ty?.kind === "message") return `${this.msgRef(e.base)}->${e.name}`;
        return `${this.expr(e.base)}.${e.name}`;
      }
      case "Unary":
        return e.postfix ? `(${this.expr(e.operand)}${e.op})` : `(${e.op}${this.expr(e.operand)})`;
      case "Binary":
        if (e.op === ",") return `(${this.expr(e.left)}, ${this.expr(e.right)})`;
        return `(${this.expr(e.left)} ${e.op} ${this.expr(e.right)})`;
      case "Cond":
        return `(${this.expr(e.cond)} ? ${this.expr(e.then)} : ${this.expr(e.otherwise)})`;
      case "Assign": {
        if (e.target.kind === "Call" && e.target.callee.kind === "Member") {
          const acc = MSG_ACCESSORS[e.target.callee.name];
          if (acc && acc.size === 1) {
            return `CAPL_SETB(${this.msgRef(e.target.callee.base)}, ${this.expr(e.target.args[0])}, ${this.expr(e.value)})`;
          }
        }
        return `(${this.expr(e.target)} ${e.op} ${this.expr(e.value)})`;
      }
      case "Call": return this.call(e);
    }
  }

  private msgRef(e: A.Expr): string {
    if (e.kind === "This") return "this_msg";
    return `(&${this.expr(e)})`;
  }

  private call(e: A.CallExpr): string {
    if (e.callee.kind === "Member") {
      const acc = MSG_ACCESSORS[e.callee.name];
      const idx = e.args[0] ? this.expr(e.args[0]) : "0";
      const ref = this.msgRef(e.callee.base);
      if (acc?.size === 1) return `CAPL_B(${ref}, ${idx})`;
      if (acc?.size === 2) return `CAPL_W(${ref}, ${idx})`;
      return `CAPL_D(${ref}, ${idx})`;
    }
    const name = e.callee.kind === "Ident" ? e.callee.name : "(*unknown)";
    const args = e.args.map((a) => this.expr(a));
    switch (name) {
      case "write": return `capl_write(${args.join(", ")})`;
      case "setTimer": return `capl_set_timer(${args.join(", ")})`;
      case "setTimerCyclic": return `capl_set_timer_cyclic(${args.join(", ")})`;
      case "cancelTimer": return `capl_cancel_timer(${args.join(", ")})`;
      case "output": return `capl_output(${this.msgRef(e.args[0])})`;
      case "timeNow": return "capl_time_now()";
      case "random": return `capl_random(${args.join(", ")})`;
      case "canOnline": return "capl_can_online()";
      case "canOffline": return "capl_can_offline()";
      case "stopMeasurement": return "capl_stop_measurement()";
      case "elCount": {
        const t = e.args[0]?.ty;
        return String(t?.kind === "array" ? t.len ?? 0 : 0);
      }
      case "abs": return `((${args[0]}) < 0 ? -(${args[0]}) : (${args[0]}))`;
      case "min": return `((${args[0]}) < (${args[1]}) ? (${args[0]}) : (${args[1]}))`;
      case "max": return `((${args[0]}) > (${args[1]}) ? (${args[0]}) : (${args[1]}))`;
      case "strlen": return `(int32_t)strlen(${args[0]})`;
      default: return `${name}(${args.join(", ")})`;
    }
  }
}

export function emitC(sema: SemaResult): string {
  return new CBackend(sema).emit();
}
